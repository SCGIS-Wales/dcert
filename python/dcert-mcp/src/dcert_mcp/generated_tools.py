async def diagnose_endpoint(
    *,
    target: str,
    allow_legacy_tls: bool | None = None,
    ca_cert: str | None = None,
    cert_password: str | None = None,
    cipher: str | list[str] | None = None,
    cipher_list: str | None = None,
    cipher_suites: str | None = None,
    ciphers_notation: str | None = None,
    client_cert: str | None = None,
    client_key: str | None = None,
    connect_to: str | list[str] | None = None,
    data: str | None = None,
    groups: str | None = None,
    headers: list[str] | None = None,
    http_protocol: str | None = None,
    method: str | None = None,
    no_verify: bool = False,
    noproxy: str | None = None,
    pkcs12: str | None = None,
    pq_probe: bool | None = None,
    proxy: str | None = None,
    read_timeout: int | None = None,
    resolve: str | list[str] | None = None,
    show_body: bool = False,
    sni: str | None = None,
    starttls: str | None = None,
    timeout_: int | None = None,
    tls_profile: str | None = None,
    session: Session | None = None,
    timeout: float | None = None,
) -> ToolResponse:
    """Diagnose why an HTTPS endpoint fails or misbehaves: TLS handshake failures, mutual TLS on any
    server (client certificate required, optional or rejected, detected from the server's
    CertificateRequest on TLS 1.2 and 1.3), Apigee runtime faults (target TLS handshake failures,
    unreachable or slow targets, policy faults), Envoy and Istio upstream errors, nginx client
    certificate errors, Amazon CloudFront (edge generated 4xx/5xx pages, origin errors forwarded by
    the edge, viewer mTLS, origin mTLS gaps, security policy mismatches), Amazon API Gateway
    (gateway responses such as Missing Authentication Token, Forbidden, throttling, integration
    timeouts and 5xx, mutual TLS custom domains, private API endpoints), forward web proxies
    (CONNECT 407/403/5xx, wrong proxy scheme, HTTP_PROXY only environments) and TLS inspection
    (chains re signed by Zscaler, Netskope and similar gateways). Probes the target, captures the
    TLS handshake, certificate chain, HTTP status, headers and a bounded body excerpt, and scores
    them against the diagnostics knowledge base. Returns JSON findings ordered earliest layer first,
    each with a confidence figure, the evidence that matched, a root cause and remediation steps,
    plus `platforms` (the products fingerprinted from headers, body, host and chain; vendor specific
    findings require one, so a non AWS endpoint never gets CloudFront or API Gateway advice) and
    `context` notes explaining what the status, headers and body sentences of a CloudFront or API
    Gateway response mean. Supports mTLS, connection overrides and per request proxy settings like
    analyze_certificate.

    Args:
        target: HTTPS URL or hostname to probe (a gateway, CDN, origin or any TLS endpoint)
        allow_legacy_tls: Allow TLS 1.0 and 1.1 (deprecated by RFC 8996) at OpenSSL security level 0
            for this probe. With no minimum version given, the probe then also offers TLS 1.0 and
            1.1 (default: false)
        ca_cert: Custom CA certificate bundle PEM file (overrides system CAs)
        cert_password: Password for the PKCS12 file
        cipher: Cipher suites to offer, each in any notation: IANA name
            ("TLS_ECDHE_RSA_WITH_AES_128_GCM_SHA256"), OpenSSL name ("ECDHE-RSA-AES128-GCM-SHA256")
            or code point ("0xC02F", "C02F", "0xC0,0x2F"). A single string or a list; TLS 1.2 and
            1.3 suites may be mixed. Naming one family only limits the handshake to that version.
            Cannot be combined with `cipher_list` or `cipher_suites`.
        cipher_list: OpenSSL cipher string for TLS 1.2 and below (e.g. "ECDHE+AESGCM:CHACHA20"),
            passed as is
        cipher_suites: Colon-separated IANA cipher names for TLS 1.3 (e.g. "TLS_AES_256_GCM_SHA384")
        ciphers_notation: How the negotiated cipher is reported: "all" (default; a record with the
            OpenSSL and IANA names, code point, protocol, forward secrecy and AEAD), or "iana" or
            "openssl" for that name alone
        client_cert: Client certificate PEM file path for mutual TLS authentication
        client_key: Client private key PEM file path for mutual TLS (must be used with client_cert)
        connect_to: Redirect the connection to another host or IP while `target`'s hostname is still
            used for SNI, the Host header and certificate validation. Use this to analyze a specific
            server/backend behind a load balancer or DNS round-robin, or when the hostname does not
            resolve from here. Accepts a bare IP address, or curl's "HOST1:PORT1:HOST2:PORT2" form
            (empty fields mean any/unchanged) when the destination is a hostname or a different
            port. A single string or a list of strings. Like curl's --connect-to. Examples:
            target='https://api.example.com' with connect_to='10.0.0.5', or
            connect_to='api.example.com:443:origin.internal:8443'.
        data: Request body data string (implies POST if method is GET)
        groups: Key exchange groups to offer, as an OpenSSL group list (e.g.
            "X25519MLKEM768:X25519:secp384r1"). RFC 10024 post quantum hybrids need OpenSSL 3.5 or
            later on the dcert host.
        headers: Custom HTTP headers as "Key:Value" strings (repeatable)
        http_protocol: HTTP protocol version: "http1-1" or "http2" (default: http1-1)
        method: HTTP method: "GET", "POST", "HEAD", "OPTIONS" (default: GET)
        no_verify: Accept the server certificate without verification so the HTTP layer can still be
            probed (default: false). Refused unless the server sets DCERT_MCP_ALLOW_NO_VERIFY=1.
        noproxy: Comma-separated hosts that must bypass the proxy, overriding NO_PROXY. "*" bypasses
            the proxy entirely; an empty string clears an inherited NO_PROXY. Like curl's --noproxy.
        pkcs12: PKCS12/PFX file containing client cert + key (alternative to client_cert/client_key)
        pq_probe: Run a second handshake offering only the RFC 10024 hybrid post quantum groups and
            report whether the server supports post quantum key agreement (`post_quantum_probe` in
            the connection block).
        proxy: Forward proxy URL for this request, overriding the HTTPS_PROXY/HTTP_PROXY environment
            variables the server inherited. Must be http:// (https:// proxies are refused until TLS
            to the proxy is implemented); credentials may be embedded
            (http://user:pass@proxy.corp:3128). Pass an empty string to force a direct connection.
            Note that `connect_to` and `resolve` always bypass the proxy.
        read_timeout: Read timeout in seconds (default: 5)
        resolve: Pin "HOST:PORT" to specific IP addresses instead of using DNS, like curl's
            --resolve. The hostname is still used for SNI, the Host header and certificate
            validation. Format "HOST:PORT:ADDRESS", where HOST may be "*" and ADDRESS may be several
            comma-separated IPs tried in order. Only IP addresses are accepted here — use
            `connect_to` for a hostname. A single string or a list of strings. Example:
            'api.example.com:443:10.0.0.5'.
        show_body: Include the captured response body excerpt in the output even when no finding
            cites it (default: false)
        sni: Override the SNI (Server Name Indication) hostname sent in the TLS handshake. Most
            callers do NOT need this. To connect to an IP while validating a hostname, prefer
            `connect_to` (keep the hostname in `target`); use `sni` only to send a SNI value that
            differs from the validated hostname. Example: target='https://10.0.0.5',
            sni='api.example.com'.
        starttls: STARTTLS protocol: "smtp", "imap", "pop3", "ftp". When set, target is treated as
            host[:port]
        timeout_: Connection timeout in seconds (default: 10)
        tls_profile: Named TLS client profile: "modern" (TLS 1.3 only) or "intermediate" (TLS 1.2
            and 1.3, forward secret AEAD suites), following the Mozilla configurator v6. Explicit
            cipher, suite and group values win.
        session: Session to use; the shared default when ``None``.
        timeout: Per call timeout in seconds.
    """
    arguments = build_arguments(
        "diagnose_endpoint",
        {
            "target": target,
        },
        {
            "allow_legacy_tls": allow_legacy_tls,
            "ca_cert": ca_cert,
            "cert_password": cert_password,
            "cipher": cipher,
            "cipher_list": cipher_list,
            "cipher_suites": cipher_suites,
            "ciphers_notation": ciphers_notation,
            "client_cert": client_cert,
            "client_key": client_key,
            "connect_to": connect_to,
            "data": data,
            "groups": groups,
            "headers": headers,
            "http_protocol": http_protocol,
            "method": method,
            "noproxy": noproxy,
            "pkcs12": pkcs12,
            "pq_probe": pq_probe,
            "proxy": proxy,
            "read_timeout": read_timeout,
            "resolve": resolve,
            "sni": sni,
            "starttls": starttls,
            "timeout": timeout_,
            "tls_profile": tls_profile,
        },
        {
            "no_verify": (no_verify, False),
            "show_body": (show_body, False),
        },
    )
    return await call_tool("diagnose_endpoint", arguments, session=session, timeout=timeout)


