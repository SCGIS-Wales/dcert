#!/usr/bin/env python3
"""Generate typed async wrappers for the dcert-mcp tools that have none.

``dcert_mcp.tools`` has hand-written wrappers for 17 tools; the server has
more. This script reads ``tools/list`` from a built ``dcert-mcp``, skips every
tool that ``tools.py`` already wraps (their signatures stay as they are), and
writes one keyword-only wrapper per remaining tool to
``python/dcert-mcp/src/dcert_mcp/generated_tools.py``, typed from the tool's
JSON schema. CI regenerates it with ``--check`` and fails when the committed
file differs, so the Python client cannot fall behind the server again.

Usage::

    python scripts/gen_typed_tools.py --binary target/release/dcert-mcp
    python scripts/gen_typed_tools.py --binary target/release/dcert-mcp --check
"""

from __future__ import annotations

import json
import keyword
import re
import subprocess
import sys
import textwrap
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import Any

import click

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "python" / "dcert-mcp" / "src" / "dcert_mcp"
OUTPUT = PACKAGE / "generated_tools.py"
HANDWRITTEN = PACKAGE / "tools.py"
#: Wrapper parameters every function has; a tool argument with the same name
#: gets a trailing underscore (PEP 8) and is sent under its own name.
WRAPPER_PARAMETERS = frozenset({"session", "timeout"})
WIDTH = 100
HANDSHAKE = [
    {
        "jsonrpc": "2.0",
        "id": 1,
        "method": "initialize",
        "params": {
            "protocolVersion": "2025-11-25",
            "capabilities": {},
            "clientInfo": {"name": "gen-typed-tools", "version": "0"},
        },
    },
    {"jsonrpc": "2.0", "method": "notifications/initialized"},
    {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
]

HEADER = '''\
"""Typed async wrappers for the dcert-mcp tools without a hand-written one.

Generated by ``scripts/gen_typed_tools.py`` from the server's ``tools/list``;
do not edit. CI fails when this file is out of date. Each function takes
keyword arguments named as in the tool's schema (a name that clashes with
``session`` or ``timeout`` gets a trailing underscore), sends only the
arguments that differ from the server's defaults, and returns the tool's
response like the functions in :mod:`dcert_mcp.tools`.
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable
{typing_import}
from dcert_mcp.tools import Session, ToolResponse, build_arguments, call_tool
'''


def handwritten_tools(source: str) -> set[str]:
    return set(re.findall(r"^async def ([a-z_]+)\(", source, re.MULTILINE))


def python_name(name: str) -> str:
    if name in WRAPPER_PARAMETERS or keyword.iskeyword(name):
        return name + "_"
    return name


def resolve(schema: Mapping[str, Any], defs: Mapping[str, Any]) -> Mapping[str, Any]:
    ref = schema.get("$ref")
    if isinstance(ref, str) and ref.startswith("#/$defs/"):
        return resolve(defs[ref.removeprefix("#/$defs/")], defs)
    return schema


def annotation(schema: Mapping[str, Any], defs: Mapping[str, Any]) -> tuple[str, bool]:
    """``(type, nullable)`` for one JSON schema."""
    schema = resolve(schema, defs)
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts: list[str] = []
            nullable = False
            for option in schema[key]:
                text, null = annotation(option, defs)
                nullable = nullable or null
                if text != "None":
                    parts.extend(p for p in text.split(" | ") if p not in parts)
            return (" | ".join(parts) or "Any"), nullable
    kinds = schema.get("type", "any")
    kinds = list(kinds) if isinstance(kinds, list) else [kinds]
    nullable = "null" in kinds
    names: list[str] = []
    for kind in (k for k in kinds if k != "null"):
        if kind == "array":
            item, _ = annotation(schema.get("items", {}), defs)
            names.append(f"list[{item}]")
        else:
            names.append(
                {
                    "string": "str",
                    "integer": "int",
                    "number": "float",
                    "boolean": "bool",
                    "object": "dict[str, Any]",
                }.get(kind, "Any")
            )
    if not names:
        return ("None" if nullable else "Any"), nullable
    return " | ".join(names), nullable


def literal(value: object) -> str:
    if isinstance(value, bool) or value is None:
        return repr(value)
    if isinstance(value, (int, float)):
        return repr(value)
    return json.dumps(value)


def wrap(text: str, first: str, rest: str) -> list[str]:
    """``text`` as one docstring paragraph, wrapped to the line length."""
    clean = " ".join(text.split()).replace("\\", "\\\\").replace('"""', "'''")
    lines = textwrap.wrap(
        clean,
        WIDTH,
        initial_indent=first,
        subsequent_indent=rest,
        break_long_words=False,
        break_on_hyphens=False,
    )
    return lines or [first.rstrip()]


def wrapper(tool: Mapping[str, Any]) -> str:
    """The source of one wrapper function."""
    name = str(tool["name"])
    schema = tool.get("inputSchema") or {}
    defs = schema.get("$defs") or {}
    properties: Mapping[str, Any] = schema.get("properties") or {}
    required = [p for p in properties if p in set(schema.get("required") or [])]
    others = [p for p in properties if p not in required]

    params: list[str] = ["    *,"]
    required_args: list[str] = []
    optional_args: list[str] = []
    defaulted_args: list[str] = []
    docs: list[str] = []
    for prop in [*required, *others]:
        spec = properties[prop]
        arg = python_name(prop)
        kind, nullable = annotation(spec, defs)
        default = spec.get("default")
        if prop in required:
            params.append(f"    {arg}: {kind},")
            required_args.append(f'            "{prop}": {arg},')
        elif default is None or default == [] or default == {}:
            params.append(f"    {arg}: {kind} | None = None,")
            optional_args.append(f'            "{prop}": {arg},')
        else:
            params.append(f"    {arg}: {kind} = {literal(default)},")
            defaulted_args.append(f'            "{prop}": ({arg}, {literal(default)}),')
        del nullable
        description = str(spec.get("description") or resolve(spec, defs).get("description") or "")
        docs.extend(wrap(f"{arg}: {description}".rstrip(": "), " " * 8, " " * 12))
    params += ["    session: Session | None = None,", "    timeout: float | None = None,"]
    docs += [
        "        session: Session to use; the shared default when ``None``.",
        "        timeout: Per call timeout in seconds.",
    ]

    def block(entries: Sequence[str]) -> list[str]:
        return ["        {", *entries, "        },"] if entries else ["        {},"]

    body = [
        "    arguments = build_arguments(",
        f'        "{name}",',
        *block(required_args),
        *block(optional_args),
        *block(defaulted_args),
        "    )",
        f'    return await call_tool("{name}", arguments, session=session, timeout=timeout)',
    ]
    description = str(tool.get("description") or name)
    doc = wrap(description, '    """', "    ")
    doc += ["", "    Args:", *docs, '    """']
    return "\n".join([f"async def {name}(", *params, ") -> ToolResponse:", *doc, *body])


def render(tools: Iterable[Mapping[str, Any]], skip: set[str]) -> str:
    chosen = sorted((t for t in tools if t["name"] not in skip), key=lambda t: str(t["name"]))
    functions = [wrapper(t) for t in chosen]
    listing = "\n".join(f"    {t['name']}," for t in chosen)
    uses_any = any(re.search(r"\bAny\b", f) for f in functions)
    header = HEADER.format(typing_import="from typing import Any\n" if uses_any else "")
    return (
        header
        + "\n\n"
        + "\n\n\n".join(functions)
        + "\n\n\n"
        + "#: Every generated wrapper, in name order.\n"
        + "GENERATED_TOOL_FUNCTIONS: tuple[Callable[..., Awaitable[ToolResponse]], ...] = (\n"
        + listing
        + "\n)\n"
    )


def server_tools(binary: Path) -> list[dict[str, Any]]:
    with subprocess.Popen(  # noqa: S603 - the built server, fixed arguments
        [str(binary)],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
    ) as proc:
        if proc.stdin is None or proc.stdout is None:
            raise click.ClickException("could not open the server's stdio")
        proc.stdin.write("".join(json.dumps(m) + "\n" for m in HANDSHAKE))
        proc.stdin.flush()
        for line in proc.stdout:
            message = json.loads(line)
            if message.get("id") == 2:
                proc.kill()
                return list(message["result"]["tools"])
        proc.kill()
    raise click.ClickException(f"{binary} did not answer tools/list")


@click.command()
@click.option("--binary", type=click.Path(path_type=Path, dir_okay=False), required=True)
@click.option("--output", type=click.Path(path_type=Path), default=OUTPUT, show_default=True)
@click.option("--check", is_flag=True, help="Fail when the file differs instead of writing it.")
def main(binary: Path, output: Path, check: bool) -> None:
    """Write (or with --check, compare) the generated wrappers."""
    skip = handwritten_tools(HANDWRITTEN.read_text(encoding="utf-8"))
    text = render(server_tools(binary), skip)
    if check:
        if not output.exists() or output.read_text(encoding="utf-8") != text:
            click.echo(
                f"::error::{output} is out of date; run: python scripts/gen_typed_tools.py "
                "--binary target/release/dcert-mcp",
                err=True,
            )
            sys.exit(1)
        click.echo(f"{output.name} is current")
        return
    output.write_text(text, encoding="utf-8")
    click.echo(f"wrote {output}")


if __name__ == "__main__":
    main()
