#!/usr/bin/env python3
"""Write and check the trust anchors embedded for root trust classification.

``webpki-root-certs`` (the embedded Mozilla set dcert classifies against)
holds only the roots Mozilla trusts for websites. Two other groups of publicly
operated roots are embedded from ``scripts/trust_anchors.yaml``:

* the roots Mozilla trusts for email (S/MIME) and not for websites, such as
  Sectigo Public Email Protection Root R46 and E46, read from NSS's
  ``certdata.txt`` at a pinned release tag whose SHA-256 is recorded;
* the X9 Financial PKI roots and intermediates (DigiCert), committed as PEM
  files and checked against the fingerprints DigiCert publishes.

Usage::

    python scripts/gen_trust_anchors.py            # (re)write the Mozilla email set
    python scripts/gen_trust_anchors.py --check    # verify everything, write nothing

``--check`` recomputes the email set from the pinned ``certdata.txt`` and
compares it with the committed file, and recomputes the SHA-256 of every X9
file. It needs network access for the certdata download.
"""

from __future__ import annotations

import base64
import hashlib
import re
import sys
import urllib.request
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import click
import yaml

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "scripts" / "trust_anchors.yaml"
TIMEOUT = 60
PEM = re.compile(rb"-----BEGIN CERTIFICATE-----\s*(.+?)\s*-----END CERTIFICATE-----", re.S)


@dataclass(frozen=True)
class NssRoot:
    """One certificate of certdata.txt with its trust bits."""

    label: str
    der: bytes
    server: bool
    email: bool
    email_distrust_after: bool


def octal(lines: list[str]) -> bytes:
    """The bytes of a ``MULTILINE_OCTAL`` block (``\\060\\202...`` lines)."""
    text = "".join(lines)
    return bytes(int(match, 8) for match in re.findall(r"\\([0-7]{3})", text))


def objects(text: str) -> Iterator[dict[str, Any]]:
    """The objects of certdata.txt as ``{attribute: value}`` maps."""
    current: dict[str, Any] = {}
    lines = iter(text.splitlines())
    for line in lines:
        if not line.strip() or line.startswith("#"):
            if current:
                yield current
                current = {}
            continue
        parts = line.split(" ", 2)
        name = parts[0]
        if len(parts) >= 2 and parts[1] == "MULTILINE_OCTAL":
            block = []
            for inner in lines:
                if inner == "END":
                    break
                block.append(inner)
            current[name] = octal(block)
        elif len(parts) == 3:
            current[name] = parts[2]
    if current:
        yield current


def nss_roots(text: str) -> list[NssRoot]:
    """Every certificate of certdata.txt joined to its trust object by SHA-1."""
    certs: dict[bytes, dict[str, Any]] = {}
    trusts: dict[bytes, dict[str, Any]] = {}
    for obj in objects(text):
        kind = obj.get("CKA_CLASS")
        if kind == "CKO_CERTIFICATE" and "CKA_VALUE" in obj:
            certs[hashlib.sha1(obj["CKA_VALUE"]).digest()] = obj  # noqa: S324 - NSS keys trust by SHA-1
        elif kind == "CKO_NSS_TRUST" and "CKA_CERT_SHA1_HASH" in obj:
            trusts[obj["CKA_CERT_SHA1_HASH"]] = obj
    roots = []
    for sha1, cert in certs.items():
        trust = trusts.get(sha1, {})
        distrust = cert.get("CKA_NSS_EMAIL_DISTRUST_AFTER")
        roots.append(
            NssRoot(
                label=str(cert.get("CKA_LABEL", "")).strip('"'),
                der=cert["CKA_VALUE"],
                server=trust.get("CKA_TRUST_SERVER_AUTH") == "CKT_NSS_TRUSTED_DELEGATOR",
                email=trust.get("CKA_TRUST_EMAIL_PROTECTION") == "CKT_NSS_TRUSTED_DELEGATOR",
                email_distrust_after=isinstance(distrust, bytes),
            )
        )
    return roots


def email_only(roots: list[NssRoot]) -> list[NssRoot]:
    """Roots trusted for email, not for websites, and without an email distrust date."""
    chosen = [r for r in roots if r.email and not r.server and not r.email_distrust_after]
    return sorted(chosen, key=lambda r: (r.label, hashlib.sha256(r.der).hexdigest()))


def pem(der: bytes) -> str:
    body = base64.b64encode(der).decode("ascii")
    lines = [body[i : i + 64] for i in range(0, len(body), 64)]
    return "-----BEGIN CERTIFICATE-----\n" + "\n".join(lines) + "\n-----END CERTIFICATE-----\n"


def render_email(roots: list[NssRoot], tag: str) -> str:
    out = [
        f"# Roots Mozilla trusts for email (S/MIME) and not for websites, from NSS {tag}.",
        "# Generated by scripts/gen_trust_anchors.py; do not edit.",
        "",
    ]
    for root in roots:
        out.append(f"# {root.label}")
        out.append(f"# SHA-256 {hashlib.sha256(root.der).hexdigest().upper()}")
        out.append(pem(root.der))
    return "\n".join(out)


def pem_der(path: Path) -> bytes:
    match = PEM.search(path.read_bytes())
    if not match:
        raise click.ClickException(f"{path}: no PEM certificate")
    return base64.b64decode(b"".join(match[1].split()))


def x9_problems(config: dict[str, Any], root: Path = ROOT) -> list[str]:
    """Every X9 file present and matching its published SHA-256."""
    problems = []
    for anchor in config["x9_financial"]["anchors"]:
        path = root / anchor["file"]
        if not path.exists():
            problems.append(f"{anchor['file']} is missing")
            continue
        actual = hashlib.sha256(pem_der(path)).hexdigest().upper()
        if actual != anchor["sha256"].upper():
            problems.append(f"{anchor['file']}: SHA-256 {actual}, published {anchor['sha256']}")
    return problems


def certdata(spec: dict[str, Any]) -> str:
    url = spec["url"].format(tag=spec["nss_tag"])
    request = urllib.request.Request(url, headers={"User-Agent": "dcert-trust-anchors"})  # noqa: S310
    with urllib.request.urlopen(request, timeout=TIMEOUT) as response:  # noqa: S310 - https only
        data = bytes(response.read())
    digest = hashlib.sha256(data).hexdigest()
    if digest != spec["sha256"]:
        raise click.ClickException(
            f"{url}: SHA-256 {digest} differs from the pinned {spec['sha256']}"
        )
    return data.decode("utf-8")


@click.command()
@click.option("--check", is_flag=True, help="Verify the embedded anchors instead of writing.")
@click.option("--config", "config_path", type=click.Path(path_type=Path), default=CONFIG)
def main(check: bool, config_path: Path) -> None:
    """Write (or check) the embedded trust anchors."""
    config = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    spec = config["mozilla_email"]
    text = render_email(email_only(nss_roots(certdata(spec))), spec["nss_tag"])
    output = ROOT / spec["output"]
    problems = x9_problems(config)
    if check:
        if not output.exists() or output.read_text(encoding="utf-8") != text:
            problems.append(
                f"{spec['output']} is out of date; run python scripts/gen_trust_anchors.py"
            )
    else:
        output.write_text(text, encoding="utf-8")
        click.echo(f"wrote {spec['output']} ({text.count('BEGIN CERTIFICATE')} roots)")
    for problem in problems:
        click.echo(f"::error::{problem}", err=True)
    if problems:
        sys.exit(1)
    if check:
        click.echo("trust anchors match their sources")


if __name__ == "__main__":
    main()
